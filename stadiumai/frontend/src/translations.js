export function getTranslationHelper(language) {
  const lang = translations[language] || translations.en;
  return (key, fallback = "") => {
    const parts = key.split(".");
    let current = lang;
    for (const part of parts) {
      if (current && current[part] !== undefined) {
        current = current[part];
      } else {
        // Fallback to English if translation is missing in primary language
        let enCurrent = translations.en;
        for (const enPart of parts) {
          if (enCurrent && enCurrent[enPart] !== undefined) {
            enCurrent = enCurrent[enPart];
          } else {
            enCurrent = null;
            break;
          }
        }
        return enCurrent !== null ? enCurrent : fallback || key;
      }
    }
    return current;
  };
}
